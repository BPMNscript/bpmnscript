import type { editor } from '@codingame/monaco-vscode-editor-api';

/**
 * The colours a theme is built from. A site sets each as a CSS custom property,
 * `--pg-<token>` by default (see `followMonacoTheme`).
 */
export const THEME_TOKENS = [
  'bg',
  'panel',
  'raised',
  'line',
  'line-2',
  'text',
  'text-2',
  'mute',
  'error',
  'warn',
  'accent',
  'syn-keyword',
  'syn-string',
  'syn-template',
  'syn-script',
  'syn-number',
  'syn-name',
] as const;

export type ThemeToken = (typeof THEME_TOKENS)[number];
/** Each token as `#rrggbb`. */
export type ThemeColors = Record<ThemeToken, string>;

/**
 * A Monaco theme from the token colours. Rules cover the token types the BPMNscript Monarch
 * grammar emits; colours cover every widget the editor shows, so none falls back to the base theme.
 */
export function themeData(
  c: ThemeColors,
  dark: boolean,
): editor.IStandaloneThemeData {
  const fg = (hex: string) => hex.slice(1);
  // A translucent accent, as hex with alpha (Monaco takes hex only).
  const select = `${c.accent}29`;
  return {
    base: dark ? 'vs-dark' : 'vs',
    inherit: false,
    rules: [
      { token: '', foreground: fg(c.text) },
      { token: 'keyword', foreground: fg(c['syn-keyword']), fontStyle: 'bold' },
      { token: 'ID', foreground: fg(c.text) },
      { token: 'QUOTED_NAME', foreground: fg(c['syn-name']) },
      { token: 'string', foreground: fg(c['syn-string']) },
      { token: 'RAW_TEMPLATE', foreground: fg(c['syn-template']) },
      { token: 'FENCED_SCRIPT', foreground: fg(c['syn-script']) },
      { token: 'number', foreground: fg(c['syn-number']) },
      { token: 'comment', foreground: fg(c.mute), fontStyle: 'italic' },
      { token: 'operator', foreground: fg(c['text-2']) },
      { token: 'white', foreground: fg(c.text) },
    ],
    colors: {
      'editor.background': c.panel,
      'editor.foreground': c.text,
      'editorCursor.foreground': c.accent,
      'editor.selectionBackground': `${c.accent}40`,
      'editor.inactiveSelectionBackground': `${c.accent}26`,
      'editor.selectionHighlightBackground': `${c.accent}1a`,
      'editor.wordHighlightBackground': `${c['line-2']}66`,
      'editor.wordHighlightStrongBackground': `${c['line-2']}66`,
      'editor.findMatchBackground': `${c.warn}55`,
      'editor.findMatchHighlightBackground': `${c.warn}2a`,
      'editor.lineHighlightBackground': c.bg,
      'editor.lineHighlightBorder': '#00000000',
      'editorLineNumber.foreground': c.mute,
      'editorLineNumber.activeForeground': c.text,
      'editorGutter.background': c.panel,
      'editorIndentGuide.background1': c.line,
      'editorIndentGuide.activeBackground1': c['line-2'],
      'editorWhitespace.foreground': c['line-2'],
      'editorBracketMatch.background': '#00000000',
      'editorBracketMatch.border': c['line-2'],
      'editorError.foreground': c.error,
      'editorWarning.foreground': c.warn,
      'editorInfo.foreground': c.mute,
      'editorOverviewRuler.border': '#00000000',
      'editorOverviewRuler.errorForeground': c.error,
      'editorOverviewRuler.warningForeground': c.warn,
      'scrollbar.shadow': '#00000000',
      'scrollbarSlider.background': `${c['line-2']}99`,
      'scrollbarSlider.hoverBackground': c['line-2'],
      'scrollbarSlider.activeBackground': c.mute,
      focusBorder: c.accent,
      foreground: c.text,
      // Menus, hover and suggest float over the same panel colour; the shadow separates them.
      'widget.shadow': dark ? '#00000099' : '#14181b33',
      'editorWidget.background': c.raised,
      'editorWidget.foreground': c.text,
      'editorWidget.border': c['line-2'],
      'editorHoverWidget.background': c.raised,
      'editorHoverWidget.foreground': c.text,
      'editorHoverWidget.border': c['line-2'],
      'editorHoverWidget.statusBarBackground': c.bg,
      'editorSuggestWidget.background': c.raised,
      'editorSuggestWidget.foreground': c.text,
      'editorSuggestWidget.border': c['line-2'],
      'editorSuggestWidget.selectedBackground': select,
      'editorSuggestWidget.selectedForeground': c.text,
      'editorSuggestWidget.highlightForeground': c.accent,
      'editorSuggestWidget.focusHighlightForeground': c.accent,
      'list.hoverBackground': c.bg,
      'list.activeSelectionBackground': select,
      'list.activeSelectionForeground': c.text,
      'list.focusOutline': c.accent,
      'list.highlightForeground': c.accent,
      'input.background': c.panel,
      'input.foreground': c.text,
      'input.border': c['line-2'],
      'inputOption.activeBorder': c.accent,
      'textLink.foreground': c.accent,
      'textLink.activeForeground': c.accent,
      'textCodeBlock.background': c.bg,
      'editorLink.activeForeground': c.accent,
      // Context menu, command palette, peek view: none of them may fall back to the base theme's colours.
      'menu.background': c.raised,
      'menu.foreground': c.text,
      'menu.border': c['line-2'],
      'menu.selectionBackground': select,
      'menu.selectionForeground': c.text,
      'menu.separatorBackground': c.line,
      'quickInput.background': c.raised,
      'quickInput.foreground': c.text,
      'quickInputTitle.background': c.bg,
      'quickInputList.focusBackground': select,
      'quickInputList.focusForeground': c.text,
      'quickInputList.focusIconForeground': c.text,
      'pickerGroup.foreground': c.accent,
      'pickerGroup.border': c.line,
      'keybindingLabel.background': c.bg,
      'keybindingLabel.foreground': c.text,
      'keybindingLabel.border': c['line-2'],
      'keybindingLabel.bottomBorder': c['line-2'],
      'list.focusBackground': select,
      'list.focusForeground': c.text,
      'list.inactiveSelectionBackground': select,
      'list.inactiveSelectionForeground': c.text,
      descriptionForeground: c.mute,
      'peekView.border': c.accent,
      'peekViewTitle.background': c.raised,
      'peekViewTitleLabel.foreground': c.text,
      'peekViewTitleDescription.foreground': c.mute,
      'peekViewEditor.background': c.panel,
      'peekViewEditorGutter.background': c.panel,
      'peekViewEditor.matchHighlightBackground': `${c.warn}55`,
      'peekViewResult.background': c.raised,
      'peekViewResult.fileForeground': c.text,
      'peekViewResult.lineForeground': c['text-2'],
      'peekViewResult.selectionBackground': select,
      'peekViewResult.selectionForeground': c.text,
      'peekViewResult.matchHighlightBackground': `${c.warn}55`,
      'editorStickyScroll.background': c.panel,
      'inputValidation.errorBackground': c.raised,
      'inputValidation.errorBorder': c.error,
      'inputValidation.errorForeground': c.text,
    },
  };
}
